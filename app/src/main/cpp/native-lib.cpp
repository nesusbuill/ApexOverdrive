static const unsigned char KEY = 0x5A;

std::string decrypt(const unsigned char* enc, int len) {
    std::string out;
    out.reserve(len);
    for (int i = 0; i < len; i++) out += (char)(enc[i] ^ KEY);
    return out;
}

